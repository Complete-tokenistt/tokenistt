/**
 * Gets context to an agent through what it supports, without touching a file the user wrote. By default this only
 * writes files Tokenistt owns: a context file its SessionStart hook hands over, or its own Antigravity rule file.
 * Editing a shared instruction file like AGENTS.md happens only with --merge, inside a marked block, after a preview.
 */
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { CliError } from '../core/errors.js';
import type { AgentId } from '../agents/schemas.js';

export const BLOCK_START = '<!-- tokenistt:context:start (generated; edits here are replaced) -->';
export const BLOCK_END = '<!-- tokenistt:context:end -->';
export const RULE_MARKER = '<!-- generated by tokenistt; do not edit -->';

/** Each agent's limit on hook context, kept under what it would cut or move to a file. */
export const AGENT_BUDGET: Record<AgentId, number> = { 'claude-code': 2400, codex: 2000, antigravity: 4000 };

export interface InjectTarget {
  kind: 'hook' | 'rule' | 'merge';
  file: string;
  before: string;
  after: string;
  changed: boolean;
}

/** Spelled out rather than imported: the hook fast path reads this, and store/project.ts would load zod. */
export const contextFile = (root: string, agent: AgentId): string => join(root, '.tokenistt', 'context', `${agent}.md`);

const INSTRUCTION_FILE: Record<AgentId, string> = { 'claude-code': 'CLAUDE.md', codex: 'AGENTS.md', antigravity: 'AGENTS.md' };

const read = (file: string): string => (existsSync(file) ? readFileSync(file, 'utf8') : '');

export function mergeBlock(existing: string, body: string): string {
  const block = `${BLOCK_START}\n${body.trim()}\n${BLOCK_END}`;
  const start = existing.indexOf(BLOCK_START);
  const end = existing.indexOf(BLOCK_END);
  if (start !== -1 && end > start) return `${existing.slice(0, start)}${block}${existing.slice(end + BLOCK_END.length)}`;
  if (start !== -1 || end !== -1) throw new CliError('The Tokenistt block in this file is damaged: one of its markers is missing.', 1, 'Remove the leftover marker, then run this again.');
  return existing.trim() ? `${existing.trimEnd()}\n\n${block}\n` : `${block}\n`;
}

/** Works out the change without making it, so the same plan serves --dry-run, the prompt and the write. */
export function planInject(root: string, agent: AgentId, body: string, merge: boolean): InjectTarget {
  if (merge) {
    const file = join(root, INSTRUCTION_FILE[agent]);
    const before = read(file);
    const after = mergeBlock(before, body);
    return { kind: 'merge', file, before, after, changed: before !== after };
  }
  if (agent === 'antigravity') {
    const file = join(root, '.agents', 'rules', 'tokenistt.md');
    const before = read(file);
    // A file with this name that we did not write is left alone.
    if (before && !before.includes(RULE_MARKER)) throw new CliError(`${file} exists and was not generated by Tokenistt, so it was left alone.`, 1, 'Rename it, or use --merge to add a block to AGENTS.md instead.');
    const after = `${RULE_MARKER}\n${body.trim()}\n`;
    return { kind: 'rule', file, before, after, changed: before !== after };
  }
  const file = contextFile(root, agent);
  const before = read(file);
  const after = `${body.trim()}\n`;
  return { kind: 'hook', file, before, after, changed: before !== after };
}

export function applyInject(t: InjectTarget): void {
  mkdirSync(dirname(t.file), { recursive: true });
  const tmp = `${t.file}.${process.pid}.tmp`;
  writeFileSync(tmp, t.after);
  renameSync(tmp, t.file);
}

/** Removes only what Tokenistt wrote. */
export function planRemove(root: string, agent: AgentId): InjectTarget[] {
  const out: InjectTarget[] = [];
  const merged = join(root, INSTRUCTION_FILE[agent]);
  const text = read(merged);
  const start = text.indexOf(BLOCK_START);
  const end = text.indexOf(BLOCK_END);
  if (start !== -1 && end > start) {
    const after = `${text.slice(0, start).trimEnd()}\n${text.slice(end + BLOCK_END.length).trimStart()}`.trimStart();
    out.push({ kind: 'merge', file: merged, before: text, after, changed: true });
  }
  return out;
}

/** What a SessionStart hook prints to hand context to the agent, in the shape each one documents. */
export function hookOutput(agent: AgentId, context: string): string {
  if (agent === 'antigravity') return JSON.stringify({ injectSteps: [{ systemMessage: { systemMessage: context } }] });
  return JSON.stringify({ hookSpecificOutput: { hookEventName: 'SessionStart', additionalContext: context } });
}
